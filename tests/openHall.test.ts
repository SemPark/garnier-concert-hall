import test from 'node:test';
import assert from 'node:assert/strict';
import * as T from 'three';
import {separateUpperHall} from '../src/scene/OpenHall';
import {batchArchitecture} from '../src/scene/batching';
import {GOLDEN_HALL} from '../shared/goldenHall';
test('upper partition cuts transformed walls and preserves the whole organ through batching',()=>{
 const scene=new T.Scene(),wall=new T.Mesh(new T.BoxGeometry(2,20,1),new T.MeshLambertMaterial());
 wall.position.set(4,10,0);scene.add(wall);
 const organ=new T.Group();organ.userData.landmark='pipe-organ';
 const pipe=new T.Mesh(new T.BoxGeometry(1,24,1),new T.MeshLambertMaterial());pipe.position.y=12;organ.add(pipe);scene.add(organ);
 const floor=GOLDEN_HALL.balconyHeight;
 const rail=new T.Group();rail.userData.landmark='gallery-rail';rail.position.y=floor;scene.add(rail);
 rail.add(new T.Mesh(new T.BoxGeometry(2,1,.2),wall.material));
 const fixture=new T.Group();fixture.userData.landmark='panel-centre-sconce';fixture.position.y=floor+1;scene.add(fixture);
 fixture.add(new T.Mesh(new T.BoxGeometry(1,1,1),wall.material));
 const upper=separateUpperHall(scene);
 assert.equal(pipe.parent,organ);
 assert.equal(rail.parent,scene);
 assert.equal(fixture.parent,upper);
 assert.equal(fixture.children.length,1);
 assert.ok(new T.Box3().setFromObject(upper).min.y>=floor-1e-5);
 const lower=scene.children.find(o=>o instanceof T.Mesh)!;
 assert.ok(new T.Box3().setFromObject(lower).max.y<=floor+1e-5);
 const baseUpdate=batchArchitecture(scene,[]),upperUpdate=batchArchitecture(upper,[]);
 scene.add(upper);
 const camera=new T.PerspectiveCamera(90,1,.1,100);camera.position.set(0,10,30);camera.lookAt(0,10,0);camera.updateMatrixWorld();
 baseUpdate(camera);upperUpdate(camera);
 assert.ok(upper.children.some(o=>o instanceof T.InstancedMesh));
 upper.visible=false;baseUpdate(camera);upperUpdate(camera);
 assert.equal(upper.visible,false);
 assert.ok(scene.children.some(o=>o instanceof T.InstancedMesh&&o.count>0));
});
